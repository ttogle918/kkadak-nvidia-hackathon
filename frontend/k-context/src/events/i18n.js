export const LANGS = ['ko', 'en'];
export const DICT = { ko: KO, en: EN };

export function normalizeLang(l) {
  return LANGS.includes(l) ? l : 'ko';
}

/** t(lang)(key, params) — 모르는 키는 키 이름 그대로(화면에서 눈에 띄게). */
export function makeT(lang) {
  const d = DICT[normalizeLang(lang)];
  return (key, params) => {
    const raw = Object.hasOwn(d, key) ? d[key] : Object.hasOwn(KO, key) ? KO[key] : key;
    return params ? raw.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : raw;
  };
}
